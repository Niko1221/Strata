"""Generate tq2t_lut_table.h (the fork's tq2t_lut_f16 as a C array) from the hex copy.

Source of truth: tests/data/tqp/tq2t_lut_f16.hex, extracted from
agention-llama ggml/src/ggml-common.h. Run: python3 ref/tqp/gen_table.py [fork-header-path]
"""
import pathlib
import re
import sys

hex_path = pathlib.Path("tests/data/tqp/tq2t_lut_f16.hex")
if len(sys.argv) > 1:
    src = pathlib.Path(sys.argv[1]).read_text()
    m = re.search(r"GGML_TABLE_BEGIN\(uint16_t, tq2t_lut_f16, 4096\)\n(.*?)\nGGML_TABLE_END\(\)", src, re.S)
    if not m:
        raise SystemExit("tq2t_lut_f16 table not found in header")
    vals = [int(t, 16) for t in re.findall(r"0x[0-9a-fA-F]+", m.group(1))]
    if len(vals) != 4096:
        raise SystemExit(f"expected 4096 values, got {len(vals)}")
    hex_path.write_text("\n".join(f"{v:04x}" for v in vals) + "\n")
else:
    vals = [int(t, 16) for t in hex_path.read_text().split()]
    if len(vals) != 4096:
        raise SystemExit(f"{hex_path}: expected 4096 values, got {len(vals)}")

out = pathlib.Path("ref/tqp/tq2t_lut_table.h")
lines = ["/* tq2t_lut_f16: 4096 fp16 bit patterns (the TQ2_T Hyb codebook, 2048 2-D points).",
         " * Generated by ref/tqp/gen_table.py from the fork header - do not edit. */",
         "static const ggml_half tq2t_lut_f16[4096] = {"]
for i in range(0, 4096, 8):
    lines.append("    " + ", ".join(f"0x{v:04x}" for v in vals[i:i + 8]) + ",")
lines.append("};")
out.write_text("\n".join(lines) + "\n")
print(f"{out}: 4096 values")
