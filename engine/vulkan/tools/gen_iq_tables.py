#!/usr/bin/env python3
"""Generate IQ dequant lookup tables from the vendored ggml-common.h.

ggml's IQ formats dequantize through small byte tables (grids and sign maps).
The Vulkan shaders cannot include the C header, so this writes the same bytes in
two checked-in forms:

    include/strata/vulkan/iq_tables.hpp   uint8_t arrays for the CPU references
    shaders/iq_tables.glsl                const uint arrays for the GLSL shaders

Both are derived from `engine/third_party/strata-ggml/ggml/src/ggml-common.h`
so the shader and its oracle cannot drift. Re-run after a ggml table change:

    python3 engine/vulkan/tools/gen_iq_tables.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VULKAN = HERE.parent
REPO = VULKAN.parents[1]
HEADER = REPO / "engine" / "third_party" / "strata-ggml" / "ggml" / "src" / "ggml-common.h"
HPP = VULKAN / "include" / "strata" / "vulkan" / "iq_tables.hpp"
GLSL = VULKAN / "shaders" / "iq_tables.glsl"

# name -> (C type, number of entries, bytes per entry)
TABLES = {
    "kmask_iq2xs": ("uint8_t", 8, 1),
    "ksigns_iq2xs": ("uint8_t", 128, 1),
    "iq2xs_grid": ("uint64_t", 512, 8),
    "iq3xxs_grid": ("uint32_t", 256, 4),
    "iq1s_grid": ("uint64_t", 2048, 8),
}
BEGIN = re.compile(r"GGML_TABLE_BEGIN\(\s*\w+\s*,\s*(\w+)\s*,\s*(\w+)\s*\)")


def read_tables(text: str) -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        m = BEGIN.search(lines[i])
        if not m:
            i += 1
            continue
        name, count_expr = m.group(1), m.group(2)
        if name not in TABLES:
            i += 1
            continue
        ctype, count, width = TABLES[name]
        values: list[int] = []
        i += 1
        while i < len(lines) and "GGML_TABLE_END" not in lines[i]:
            values.extend(int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", lines[i]))
            i += 1
        if len(values) != count:
            raise SystemExit(f"{name}: expected {count} values, found {len(values)}")
        raw = bytearray()
        for value in values:
            raw.extend((value >> (8 * b)) & 0xff for b in range(width))   # little-endian
        out[name] = bytes(raw)
        i += 1
    missing = set(TABLES) - set(out)
    if missing:
        raise SystemExit("tables not found: " + ", ".join(sorted(missing)))
    return out


def emit_hpp(tables: dict[str, bytes]) -> str:
    def rows(data: bytes, per_line: int = 16) -> str:
        return ",\n".join("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + per_line])
                          for i in range(0, len(data), per_line))
    parts = [
        "// Generated by engine/vulkan/tools/gen_iq_tables.py from ggml-common.h. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace strata::vulkan::iq_tables {",
        "",
    ]
    for name, (_ctype, count, width) in TABLES.items():
        parts.append(f"// {count} entries x {width} bytes from ggml-common.h")
        parts.append(f"static const uint8_t {name.upper()}[{len(tables[name])}] = {{")
        parts.append(rows(tables[name]))
        parts.append("};")
        parts.append("")
    parts.append("} // namespace strata::vulkan::iq_tables")
    return "\n".join(parts) + "\n"


def emit_glsl(tables: dict[str, bytes]) -> str:
    lines = [
        "// Generated by engine/vulkan/tools/gen_iq_tables.py from ggml-common.h. Do not edit.",
        "// Bytes are packed little-endian into uint words; use iq_byte() to read one.",
        "",
    ]
    for name in TABLES:
        data = tables[name]
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        # 16 uints per line keeps the shader readable and glslang fast enough.
        body = []
        for i in range(0, len(words), 16):
            body.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 16]))
        lines.append(f"const uint {name.upper()}_U32[{len(words)}] = uint[](")
        lines.append(",\n".join(body))
        lines.append(");")
        lines.append("")
    lines.extend([
        "// One byte of a little-endian packed uint word. Call with",
        "// TABLE[byte_index >> 2u] and (byte_index & 3u): GLSL 450 needs a",
        "// sized array parameter, so the array is indexed at the call site.",
        "uint iq_byte(uint word, uint byte_in_word) {",
        "    return (word >> (byte_in_word * 8u)) & 255u;",
        "}",
        "",
        "// ggml's uint64 grid entries are eight signed bytes: grid[j] + delta.",
        "int iq_sbyte(uint word, uint byte_in_word) {",
        "    uint b = iq_byte(word, byte_in_word);",
        "    return int(b) - (b >= 128u ? 256 : 0);",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    if not HEADER.is_file():
        print(f"missing {HEADER}", file=sys.stderr)
        return 2
    tables = read_tables(HEADER.read_text(encoding="utf-8"))
    HPP.parent.mkdir(parents=True, exist_ok=True)
    HPP.write_text(emit_hpp(tables), encoding="utf-8")
    GLSL.parent.mkdir(parents=True, exist_ok=True)
    GLSL.write_text(emit_glsl(tables), encoding="utf-8")
    print(f"wrote {HPP} ({sum(len(v) for v in tables.values())} bytes)")
    print(f"wrote {GLSL}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
