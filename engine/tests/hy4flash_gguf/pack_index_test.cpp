// Read hand-written v3 and v4 pack indices to exercise both layouts.
#include "strata/core/weights.hpp"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <set>
#include <string>

namespace fs = std::filesystem;
using strata::core::WeightTable;

namespace {
int g_fail = 0;

void check(bool ok, const std::string& what) {
    std::printf("  %-78s %s\n", what.c_str(), ok ? "ok" : "FAIL");
    if (!ok) ++g_fail;
}

/// A row of 19 (v3) or 20 (v4) fields.  `dst_bytes` 0 with `code_bits` non-zero is the shape-only form.
std::string row_v3(const char* name, int kind, uint64_t dst_bytes, int64_t ne0, int64_t ne1, int code_bits) {
    char b[512];
    std::snprintf(b, sizeof b, "%s 0 %d 0 0 0 %llu %lld %lld %d 0 32 0 0 0 0 0 0 0", name, kind,
                  (unsigned long long) dst_bytes, (long long) ne0, (long long) ne1, code_bits);
    return b;
}
std::string row_v4(const char* name, int kind, uint64_t dst_bytes, int64_t ne0, int64_t ne1, int64_t ne2,
                   int code_bits) {
    char b[512];
    std::snprintf(b, sizeof b, "%s 0 %d 0 0 0 %llu %lld %lld %lld %d 0 32 0 0 0 0 0 0 0", name, kind,
                  (unsigned long long) dst_bytes, (long long) ne0, (long long) ne1, (long long) ne2, code_bits);
    return b;
}

void write_index(const fs::path& dir, const std::string& header, const std::vector<std::string>& rows) {
    fs::create_directories(dir);
    std::ofstream f(dir / "index.txt");
    if (!header.empty()) f << header << "\n";
    f << "# align 64 pool 4096 tensors " << rows.size() << "\n";
    for (const std::string& r : rows) f << r << "\n";
}

}  // namespace

int main() {
    const fs::path dir = fs::temp_directory_path() / "strata_hy4_flash_pack_index_test";
    fs::remove_all(dir);

    // The same three tensors in both versions: one float row with bytes, one quantized row the GGUF serves
    // (shape only), and one quantized row the pack does carry.
    const std::vector<std::string> v3 = {
        row_v3("output_norm.weight", 2, 12288, 3072, 0, 0),
        row_v3("blk.0.attn_output.weight", 0, 0, 3072, 8192, 8),   // shape only: the GGUF form serves it
        row_v3("blk.1.ple_key.weight", 0, 4096, 2560, 320, 4),
    };
    const std::vector<std::string> v4 = {
        row_v4("output_norm.weight", 2, 12288, 3072, 0, 0, 0),
        row_v4("blk.0.attn_output.weight", 0, 0, 3072, 8192, 0, 8),
        row_v4("blk.1.ple_key.weight", 0, 4096, 2560, 320, 0, 4),
        // what v4 is for: a tensor this model keeps per head
        row_v4("blk.0.attn_k_b.weight", 0, 0, 192, 512, 32, 8),
    };

    write_index(dir / "noversion", "", v3);
    write_index(dir / "v3", "# strata pack index v3 -- generated by tools/iq_pack.py", v3);
    write_index(dir / "v4", "# strata pack index v4 -- generated by tools/iq_pack.py", v4);
    write_index(dir / "v9", "# strata pack index v9 -- from a newer packer", v4);

    std::printf("code_bits reads the same column in both versions\n");
    for (const char* which : {"noversion", "v3"}) {
        std::string err;
        int bits = -42;
        const bool ok = WeightTable::index_code_bits((dir / which).string(), "blk.1.ple_key.weight", bits, err);
        check(ok && bits == 4, std::string(which) + ": blk.1.ple_key.weight has code_bits 4" +
                                   (ok ? "" : " (" + err + ")"));
        bits = -42;
        WeightTable::index_code_bits((dir / which).string(), "output_norm.weight", bits, err);
        check(bits == 0, std::string(which) + ": an unquantized row has code_bits 0");
    }
    {
        std::string err;
        int bits = -42;
        const bool ok = WeightTable::index_code_bits((dir / "v4").string(), "blk.1.ple_key.weight", bits, err);
        // Reading a v4 row as v3 would take ne2 (0) for code_bits here, which is the bug this guards.
        check(ok && bits == 4, "v4: the same row still has code_bits 4, not ne2" + (ok ? "" : " (" + err + ")"));
        bits = -42;
        WeightTable::index_code_bits((dir / "v4").string(), "blk.0.attn_k_b.weight", bits, err);
        check(bits == 8, "v4: a three-dimensional row's code_bits is read past ne2");
        bits = -42;
        WeightTable::index_code_bits((dir / "v4").string(), "absent.weight", bits, err);
        check(bits == -1, "a name with no row comes back -1");
    }

    std::printf("index_shape_only finds the rows the loader would refuse\n");
    for (const char* which : {"noversion", "v3", "v4"}) {
        std::string err;
        std::set<std::string> out;
        const bool ok = WeightTable::index_shape_only((dir / which).string(), out, err);
        const bool want_k_b = std::string(which) == "v4";
        const size_t want = want_k_b ? 2u : 1u;
        check(ok && out.size() == want,
              std::string(which) + ": " + std::to_string(want) + " shape-only row(s)" +
                  (ok ? ", got " + std::to_string(out.size()) : " (" + err + ")"));
        check(out.count("blk.0.attn_output.weight") == 1, std::string(which) + ": the quantized GGUF-served row");
        check(out.count("output_norm.weight") == 0, std::string(which) + ": not the float row that has bytes");
        check(out.count("blk.1.ple_key.weight") == 0, std::string(which) + ": not a quantized row the pack holds");
        if (want_k_b)
            check(out.count("blk.0.attn_k_b.weight") == 1, "v4: the three-dimensional GGUF-served row too");
    }

    std::printf("a version this engine does not know\n");
    {
        std::string err;
        uint64_t pool = 0;
        // pool_bytes does not read the version line, so it is `load` that must refuse - checked through the
        // reader that does: a v9 file's rows are not assumed to be v4's.
        (void) WeightTable::pool_bytes((dir / "v9").string(), pool, err);
        std::set<std::string> out;
        std::string e2;
        const bool ok = WeightTable::index_shape_only((dir / "v9").string(), out, e2);
        // index_shape_only reads v9 rows as v4's trailing columns, which is why `load` is the one that refuses;
        // what matters here is that it does not crash or invent rows.
        check(ok, "index_shape_only does not fail on an unknown version (load is what refuses it)");
    }

    fs::remove_all(dir);
    std::printf("%s\n", g_fail ? "FAILED" : "all ok");
    return g_fail ? 1 : 0;
}
