#!/usr/bin/env python3
"""metal/tools/gen_tqp_ref.py - writes the agention fork's TQP decoder out of its ggml-quants.c for the
parity test (metal/tests/tqp_parity.cpp), without building the fork's whole ggml:

    python3 metal/tools/gen_tqp_ref.py <fork-ggml-src-dir> [out.c]

The file carries the fork's `TQP5 / TQP6 / TQP7` section of ggml-quants.c verbatim (the decoder is the
format's definition), its tq2t_lut_f16 codebook table from ggml-common.h, and the few helpers that section
needs (tq2t_lut_val, tq2t_hyb_index, tqp_state, the block structs), plus the three entry points the test
calls.  It is generated at build time (metal/CMakeLists.txt), not committed.
"""
import pathlib
import sys


def main():
    src_dir = pathlib.Path(sys.argv[1]).resolve()
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else src_dir / "tqp_ref.c"
    quants = (src_dir / "ggml-quants.c").read_text()
    common = (src_dir / "ggml-common.h").read_text()
    i = quants.index("// ====================== TQP5 / TQP6 / TQP7")
    j = quants.index("size_t quantize_q4_0", i)
    sec = quants[i:j]
    k = common.index("GGML_TABLE_BEGIN(uint16_t, tq2t_lut_f16, 4096)")
    e = common.index("GGML_TABLE_END()", k)
    lut = common[k + len("GGML_TABLE_BEGIN(uint16_t, tq2t_lut_f16, 4096)"):e]
    # the table opens with a "#endif" (the CUDA/HIP device-copy branch above it) - not carried over
    lut = "\n".join(ln for ln in lut.splitlines() if ln.strip() not in ("#endif", "#else"))
    head = """// tqp_ref.c - generated by metal/tools/gen_tqp_ref.py from the agention llama.cpp fork's
// ggml/src/ggml-quants.c and ggml-common.h (MIT, the fork's license; the TQP section and the codebook
// table are the fork's, unchanged).  The fork's dequantize_row_tqp* compiled on its own, for
// metal/tests/tqp_parity.cpp.
#include <assert.h>
#include <math.h>
#include <stdint.h>
#include <string.h>

typedef uint16_t ggml_half;
#define GGML_RESTRICT
#define GGML_API
#define GGML_FP32_TO_FP16(x) ({ _Float16 _h = (_Float16) (x); uint16_t _r; __builtin_memcpy(&_r, &_h, 2); _r; })
#define GGML_FP16_TO_FP32(x) ({ float _f; _Float16 _h; __builtin_memcpy(&_h, &(x), 2); _f = (float) _h; _f; })

#define QK_TQP 128
#define TQ_STATE_BITS 15
#define TQ_STATE_MASK ((1u << TQ_STATE_BITS) - 1u)
typedef struct { ggml_half d; uint8_t qs[8*5]; } block_tqp5;
typedef struct { ggml_half d; uint8_t qs[8*6]; } block_tqp6;
typedef struct { ggml_half d; uint8_t qs[8*7]; } block_tqp7;
enum { GGML_TYPE_TQP5 = 147, GGML_TYPE_TQP6 = 148, GGML_TYPE_TQP7 = 149 };
static size_t ggml_row_size(int type, int64_t n) { (void) type; return (size_t) n / 128 * 42; }

static const uint16_t tq2t_lut_f16[4096] = {
"""
    helpers = """};

static inline float tq2t_lut_val(uint32_t i) { return GGML_FP16_TO_FP32(tq2t_lut_f16[i]); }
static inline uint32_t tq2t_hyb_index(uint32_t e) {
    const uint32_t x = ((e >> 1) & TQ_STATE_MASK) * 0x9e3779b1u;
    return (e & 1) ? ((x >> 10) & 2047u) : (x >> 21);
}
static inline uint32_t tqp_state(const uint8_t * qs, int k, int t) {
    const uint32_t nbytes = 8u*(uint32_t) k;
    const uint32_t off    = (uint32_t) (63 - t) * (uint32_t) k;
    const uint32_t i0     = off >> 3;
    const uint32_t i1     = (i0 + 1) % nbytes;
    const uint32_t i2     = (i0 + 2) % nbytes;
    const uint32_t w      = (uint32_t) qs[i0] | ((uint32_t) qs[i1] << 8) | ((uint32_t) qs[i2] << 16);
    return (w >> (off & 7)) & 0xffffu;
}

"""
    tail = """
// the entry points metal/tests/tqp_parity.cpp calls (the fork's dequantize_row_tqp*, the same bytes)
void ggml_ref_dequantize_row_tqp5(const void * x, float * y, int64_t k) { dequantize_row_tqp5((const block_tqp5 *) x, y, k); }
void ggml_ref_dequantize_row_tqp6(const void * x, float * y, int64_t k) { dequantize_row_tqp6((const block_tqp6 *) x, y, k); }
void ggml_ref_dequantize_row_tqp7(const void * x, float * y, int64_t k) { dequantize_row_tqp7((const block_tqp7 *) x, y, k); }
"""
    out.write_text(head + lut + helpers + sec + tail)
    print("wrote %s (%d bytes)" % (out, out.stat().st_size))


if __name__ == "__main__":
    main()
