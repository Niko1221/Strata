def synthetic_rows(n, seed=1):
    """n IQ4_NL rows of 90 B: random codes, fp16 scales of about the real size and either sign."""
    rng = np.random.default_rng(seed)
    b = rng.integers(0, 256, (n, 5, 18), dtype=np.uint8)
    d = (rng.uniform(5e-5, 3e-4, (n, 5)) * rng.choice([-1, 1], (n, 5))).astype("<f2")
    b[:, :, :2] = d.view(np.uint8).reshape(n, 5, 2)
    return b.reshape(n, 90)


def synthetic_source(path, n, seed):
    """A table-only IQ4_NL GGUF of n synthetic rows, in the layout the emulator reads (its own header writer, type 20)."""
    rows = synthetic_rows(n, seed)
    path.write_bytes(E.gguf_header(n, {"general.architecture": "strata-ple"}, 20, E.DIM) + rows.tobytes())
    return rows


def lowbit_cases(tmp, n_plain):
    """Per format: the emulator's codebook (fit_codebook on a synthetic table), its quantizer and packer on n_plain rows of
    that table plus a row past E4M3's range (saturates at 448), a tiny row (subnormal E4M3 and fp16 scales) and a zero row.
    -> [(format, codebook, packed rows, the quantizer's floats)]"""
    src = tmp / "lowbit_src.gguf"
    rows = synthetic_source(src, max(4096, n_plain), seed=11)
    X = E.iq4nl_decode(rows[:n_plain])
    X = np.concatenate([X, X[:1] * 2000, X[1:2] * 3e-5, np.zeros((1, E.DIM), np.float32)]).astype(np.float32)
    out = []
    for fmt in ("c4", "c3", "c2s"):
        cb = E.fit_codebook(E.Source(src), fmt, seed=1, ntry=7)
        Y, codes, scales, _ = E.quantize(X, np.array(cb["grid"], np.float32), cb["block"], cb["scale"], np.float32(cb["table_scale"]), 7)
        out.append((fmt, cb, E.pack_native(codes, scales, cb), Y))
    return out


