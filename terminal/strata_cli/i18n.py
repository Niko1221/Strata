def language() -> str:
    # An explicit choice wins over the locale, so STRATA_CLI_LANG=en can turn Arabic off.
    explicit = os.environ.get("STRATA_CLI_LANG")
    if explicit is not None:
        return "ar" if explicit.lower().replace("_", "-").split("-")[0] == "ar" else "en"
    for name in ("LANG", "LC_ALL", "LC_MESSAGES"):
        value = os.environ.get(name, "")
        base = value.lower().replace("_", "-").split("-")[0]
        if base == "ar":
            return "ar"
    return "en"


def enabled() -> bool:
    return language() == "ar"


def _pattern(template: str) -> re.Pattern[str]:
    parts = template.split("{}")
    return re.compile("^" + "(.*?)".join(re.escape(p) for p in parts) + "$", re.S)


_PATTERNS = sorted(
    ((_pattern(source), target) for source, target in CATALOG.items() if "{}" in source),
    key=lambda pair: len(pair[0].pattern),
    reverse=True,
)


def tr(text: Any) -> Any:
    if not isinstance(text, str) or not enabled() or not text.strip():
        return text
    if text in CATALOG:
        return CATALOG[text]
    stripped = text.strip()
    if stripped.startswith(("{", "[", "-----", "---")) or "api_key" in stripped:
        return text  # JSON, tables, keys and secrets are never translated
    for pattern, target in _PATTERNS:
        match = pattern.fullmatch(stripped)
        if match:
            values = iter(match.groups())
            return text.replace(stripped, re.sub(r"\{\}", lambda _: next(values), target))
    return text


_original_print = builtins.print


def _arabic_print(*args: Any, **kwargs: Any) -> None:
    if args and isinstance(args[0], str):
        args = (tr(args[0]), *args[1:])
        if len(args) == 1 and "\n" in args[0]:
            args = ("\n".join(tr(line) for line in args[0].split("\n")),)
    _original_print(*args, **kwargs)


def install() -> bool:
    """Translate human CLI output when Arabic is requested. Idempotent. English stays untouched."""
    if not enabled() or getattr(builtins.print, "_strata_arabic", False):
        return False
    _arabic_print._strata_arabic = True  # type: ignore[attr-defined]
    builtins.print = _arabic_print
    return True
