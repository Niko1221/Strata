_MODELS = {"qwen": {}, "qwen36": {"arch": "qwen35moe"}, "deepseek": {"arch": "deepseek41"}, "deepseek_exe": {"exe": "C:/x/strata-dsv41.exe"}}
_NAMES = ["qwen3.8-flash-next", "qwen3.8-flash-next-iq3_s", "qwen3.8-flash-next-Q2_0", "qwen3.8-flash-next-unsloth-ud-q4_k_xl", "qwen3.8-flash-next-unsloth-ud-iq4_xs-v31",
          "qwen3.8-flash-next-gyro-iq4", "qwen3.8-flash-next-coder-iq1_m", "qwen3.8-flash-next-swift-iq3_s", "swift-1.5-iq3_s", "qwen3.6-35b-a3b-ud-q4_k_xl", "deepseek-v4.1-flash", ""]


def vectors() -> dict:
    switches = []
    for model, cfg in _MODELS.items():
        for backend in ("cuda", "hip", "sycl", "metal", "cpu", None):
            for card, g in _CARDS.items():
                row = {"model": model, "backend": backend, "card": card,
                       "shows": sorted(s.id for s in speed_switches.applicable(cfg, [g], backend) if not s.terminal_only)}
                switches.append(row)
    names = [{"name": n, "supported": bool(drafting.supported_model(n, None))} for n in _NAMES]
    families = [{"family": f, "supported": bool(drafting.supported_model(None, f))} for f in ("qwen", "gyro", "unsloth", "swift", "coder", "nvfp4", "deepseek41")]
    return {"cards": _CARDS, "models": _MODELS, "switches": switches, "names": names, "families": families}


def render_vectors() -> str:
    return json.dumps(vectors(), indent=1, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    files = ((TARGET, render()), (VECTORS, render_vectors()))
    if "--check" in argv:
        bad = [str(p) for p, text in files if (p.read_text(encoding="utf-8") if p.is_file() else "") != text]
        for p in bad:
            print(f"{p} is out of date: run python -m strata_control.app_policy", file=sys.stderr)
        return 1 if bad else 0
    for path, text in files:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
