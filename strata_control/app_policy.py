"""The launch-policy tables the app's host (JavaScript) reads, generated from the Python that owns them.

`strata_control` decides the speed switches (`speed_switches.py`) and which models have a Drafting choice (`drafting.py`).  The app's host used to carry its own
copy of those tables.  It now imports `apps/host/server/policy-generated.mjs`, which this module writes, and a test (`tests/terminal/test_app_policy.py`, and
`apps/host/tests/policy-generated.test.mjs` on the JavaScript side) fails when the committed file differs from what `render()` makes now.

    python -m strata_control.app_policy            # rewrite apps/host/server/policy-generated.mjs
    python -m strata_control.app_policy --check    # exit 1 when it is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from strata_control import drafting, speed_switches

TARGET = Path(__file__).resolve().parents[1] / "apps" / "host" / "server" / "policy-generated.mjs"
VECTORS = Path(__file__).resolve().parents[1] / "apps" / "host" / "tests" / "data" / "policy-vectors.json"

HEADER = ("// GENERATED by `python -m strata_control.app_policy` from strata_control/speed_switches.py and strata_control/drafting.py. Do not edit it by hand:\n"
          "// change the Python and regenerate; tests/terminal/test_app_policy.py and apps/host/tests/policy-generated.test.mjs fail when this file is out of date.\n")


def _entries(pairs) -> dict:
    return {name: value for name, value in pairs}


def table() -> list[dict]:
    out = []
    for s in speed_switches.app_switches():
        row = {"id": s.id, "label": s.label, "hint": s.effect, "default": s.default, "env": _entries(s.env)}
        if s.legacy:
            row["legacy"] = _entries(s.legacy)
        out.append(row)
    return out


def render() -> str:
    rows = ",\n".join(" " + json.dumps(r, ensure_ascii=False, separators=(", ", ": ")) for r in table())
    return (HEADER
            + "/** The speed switches of the app's Expert settings (strata_control/speed_switches.py app_switches()): id, words, default, the environment entries outside the default. */\n"
            + f"export const SPEED_SWITCH_TABLE = [\n{rows},\n];\n"
            + "/** The families that have a Drafting choice (strata_control/drafting.py SUPPORTED_FAMILIES). */\n"
            + f"export const DRAFTING_FAMILIES = {json.dumps(list(drafting.SUPPORTED_FAMILIES))};\n"
            + "/** The model names the DFlash2 drafter was made for (strata_control/drafting.py _SUPPORTED_NAME), a case-insensitive pattern. */\n"
            + f"export const DFLASH2_MODEL_PATTERN = {json.dumps(drafting._SUPPORTED_NAME.pattern)};\n")


#: Cases the host's copies of the RULES (speedSwitchApplies, resolveDrafter) must answer as Python does.  The table above is data and is generated; the rules are code, so the
#: answers of the Python are written down here and apps/host/tests/policy-generated.test.mjs runs the host's rules over them.
