#!/usr/bin/env python3
# System V amd64 trampolines. strata_hybrid_on_hip picks the hipdual_ copy.
# Only strata's own text symbols: wrapping libstdc++ instantiations would replace the C++ runtime.
import re
import subprocess
import sys
from pathlib import Path


def parse_nm(line):
    matched = re.match(r"^[0-9a-fA-F]+\s+([A-Za-z])\s+(\S+)\s*$", line)
    if matched:
        return matched.group(2), matched.group(1)
    matched = re.match(r"^\s+([A-Za-z])\s+(\S+)\s*$", line)
    if matched:
        return matched.group(2), matched.group(1)
    return None


def text_symbols(path):
    result = subprocess.run(["nm", "-g", path], check=True, capture_output=True, text=True)
    found = set()
    for line in result.stdout.splitlines():
        parsed = parse_nm(line)
        if parsed is None:
            continue
        name, type_ = parsed
        if type_ in ("T", "W"):
            found.add(name)
    return found


def write_file(path, body):
    temporary = Path(str(path) + ".tmp")
    temporary.write_text(body)
    temporary.replace(path)


def main():
    if len(sys.argv) < 5:
        sys.exit("usage: hip-host-tramp.py ASM WRAP HIP.a LIBS...")
    asm_out = Path(sys.argv[1])
    wrap_out = Path(sys.argv[2])
    hip_archive = sys.argv[3]
    libraries = sys.argv[4:]

    cuda = set()
    for library in libraries:
        cuda.update(text_symbols(library))
    hip = text_symbols(hip_archive)

    names = []
    for name in sorted(hip):
        matched = re.match(r"^hipdual_(.+)", name)
        if matched is None:
            continue
        base = matched.group(1)
        if base not in cuda:
            continue
        # strata's namespace only. _ZNK is a const method. libstdc++ and main stay out.
        if re.match(r"^_ZN(?:K|V|KV|VK)*6strata", base) is None:
            continue
        names.append(base)
    if not names:
        sys.exit("hip-host-tramp: no shared strata host symbols")

    asm = (
        "# Generated by hip-host-tramp.py. A cross-TU call lands here, then tail-jumps\n"
        "# to the nvcc copy or the hipdual_ copy. The stack is back to the caller's\n"
        "# frame before the jump, so the callee's unwind info applies.\n"
        '.section .note.GNU-stack,"",@progbits\n'
        ".section .text\n"
    )
    wrap = ""
    for base in names:
        wrapped = f"__wrap_{base}"
        asm += (
            f".globl {wrapped}\n"
            f".type {wrapped}, @function\n"
            f"{wrapped}:\n"
            "\tpushq %rax\n"
            "\tmovq strata_hybrid_on_hip@GOTTPOFF(%rip), %rax\n"
            "\tmovl %fs:(%rax), %eax\n"
            "\ttestl %eax, %eax\n"
            "\tpopq %rax\n"
            "\tjnz 1f\n"
            f"\tjmp __real_{base}\n"
            "1:\n"
            f"\tjmp hipdual_{base}\n"
        )
        wrap += f"--wrap={base}\n"

    write_file(asm_out, asm)
    write_file(wrap_out, wrap)
    print(f"hip-host-tramp: {len(names)} host symbols", file=sys.stderr)


if __name__ == "__main__":
    main()
