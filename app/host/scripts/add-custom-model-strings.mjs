  const data = JSON.parse(readFileSync(file, 'utf8'));
  // French: a no-break space (U+00A0) before ; : ? ! (tests/french-typography-all.test.mjs).
  const typeset = lang === 'fr' ? v => v.replace(/(?<=\S) ([;:?!])/g, ' $1') : v => v;
  KEYS.forEach((k, i) => { data[k] = typeset(values[i]); });
